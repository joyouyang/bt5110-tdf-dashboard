-- [已实现 R13/R14] E Result 为 Rider(0,n)–Stage(0,n)，联合 PK 标识一条成绩。
-- [部分 R15] A p2 §5 要求每位完赛者有记录，但本模型无独立完赛名单，
-- 无法区分未完赛与漏录，需导入对账；不能强迫每位 Rider 对每段都有 Result。
-- [缺失 R18] A p2 §6：本表可插入退赛当段及以后成绩；FK 不检查退出时间。
-- [已实现于查询 W09] A p2 §5、E 派生属性：adjusted_time = finish_time
-- - time_bonus + time_penalty，见 queries.sql；任一输入 NULL 则结果 NULL。
-- bonus/penalty 的缺失表示零还是未知需明确，不能擅自把所有 NULL 当零。
CREATE TABLE Result (
    -- RE01 NOT NULL：每条成绩必须指定骑手。
    -- RE02 FK：该骑手必须存在于 Rider。
    bib_number INT NOT NULL REFERENCES Rider(bib_number),
    -- RE03 NOT NULL：每条成绩必须指定赛段。
    -- RE04 FK：该赛段必须存在于 Stage。
    stage_id INT NOT NULL REFERENCES Stage(stage_id),
    -- [部分 K11/K12] A p2 §5 明确 finish_time 单位为秒；INT 秒精度是实现选择。
    -- 当前 finish_time/rank/bonus/penalty 可 NULL；未验证非负或 rank 为正整数。
    -- >>> A12 [REQUIRED (NOT NULL) + RECOMMENDED (CHECK, DEFAULT)] -------------
    -- >>> WAS: finish_time INT,  rank INT,  time_bonus INT,  time_penalty INT,   (all nullable)
    -- >>> NOW: finish_time  INT NOT NULL CHECK (finish_time > 0),
    -- >>>      rank         INT NOT NULL CHECK (rank >= 1),
    -- >>>      time_bonus   INT NOT NULL DEFAULT 0 CHECK (time_bonus >= 0),
    -- >>>      time_penalty INT NOT NULL DEFAULT 0 CHECK (time_penalty >= 0),
    -- >>> WHY: Brief p2 point 5 records finish time and rank for every result, and adjusted
    -- >>>      time = finish time - bonus + penalty needs all three. In the CSV every row has
    -- >>>      all four values, with 0 written where there is no bonus or penalty, so DEFAULT 0
    -- >>>      answers the 'zero or unknown?' question in the comment above. Closes K11/K12.
    -- >>> ----------------------------------------------------------------------
    finish_time INT NOT NULL CHECK (finish_time > 0), -- A p2 §5 指定：秒数时长，不是一天中的时刻
    -- [待确认 D02] A p2 §5 与 E note 1 用 rank 表达冲线顺序。
    -- P 称原始数据有重复名次，但未核对源数据；不能断言作业允许并列。
    -- 当前确实允许重复 rank，本轮未擅自添加 UNIQUE(stage_id, rank)。
    -- >>> A13 [COMMENT CORRECTION, code unchanged] -----------------------------
    -- >>> NOW: keep: no UNIQUE (stage_id, rank)
    -- >>> WHY: D02/U05 say the duplicate-rank claim was not checked. Checked against
    -- >>>      individual_results.csv: in stage 13 (2023-07-18) bibs 23 and 197 are both rank
    -- >>>      108 at 1745 s, and rank 109 is unused. UNIQUE would reject provided data, so
    -- >>>      leaving it out is correct, not just unverified.
    -- >>> ----------------------------------------------------------------------
    rank INT NOT NULL CHECK (rank >= 1),
    time_bonus INT NOT NULL DEFAULT 0 CHECK (time_bonus >= 0), -- 秒
    time_penalty INT NOT NULL DEFAULT 0 CHECK (time_penalty >= 0), -- 秒
    -- RE05 联合 PK：同一骑手在同一赛段最多有一条成绩。
    -- 单独的骑手号码或赛段编号可以重复，两者的组合不能重复。
    PRIMARY KEY (bib_number, stage_id)
    -- 当前未加名次唯一约束；这是待核对的实现状态，不是已确认的作业许可。
);

-- [已实现 R16/R17] A p2 §6；E exit_before Rider(0,1)、Stage(0,n)，原因属性。
