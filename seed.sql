/* ============================================================================
   BT5110 Group 20 - official 2025 rules that the three CSVs do not contain
   Run after 02_load_data.sql.

   SOURCE: Tour de France 2025 race regulations (A.S.O.), tdf25-reglement-fr-en.pdf
   - Article 22: stage coefficients 1 to 6 (table printed under Article 23)
   - Article 24 b: points scale per coefficient, top 15 riders on each stage
   - Article 31: the French text alone is binding

   These are outside facts and stage_type cannot produce them: stages 6 and 7
   are both hilly but pay 30 and 50 to the winner, and stage 16 is a mountain
   stage that pays 30 where the others pay 20. So they are stored, in reference
   tables that leave the Task 2 schema in 01_schema as submitted.
   ============================================================================ */

DROP TABLE IF EXISTS ref_points_scale, ref_stage_coefficient CASCADE;

CREATE TABLE ref_stage_coefficient (
  stage_id    INT PRIMARY KEY REFERENCES Stage (stage_id),
  coefficient INT NOT NULL CHECK (coefficient BETWEEN 1 AND 6)
);

CREATE TABLE ref_points_scale (
  coefficient INT NOT NULL CHECK (coefficient BETWEEN 1 AND 6),
  place       INT NOT NULL CHECK (place BETWEEN 1 AND 15),
  points      INT NOT NULL CHECK (points > 0),
  PRIMARY KEY (coefficient, place)
);

