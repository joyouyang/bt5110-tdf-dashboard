-- [已实现 K01/R06] A p1 §1；E Country 键及 associated_with/come_from 的 (0,n)。
-- 国家可以没有车队、骑手或地点，不能增加要求国家必须被引用的限制。
CREATE TABLE Country (
    -- C01 PK：国家代码唯一标识国家，不允许重复。
    -- C02 NOT NULL：国家代码必须有值。
    -- [缺失 K02] A p1 §1 明确要求 ISO alpha-3 三位字母代码。
    -- 当前 TEXT+PK 不校验长度、字母或真实 ISO 成员；FR/SG 示例应改为 FRA/SGP。
    -- 仅 CHECK 长度为 3 仍不等于有效 ISO 代码；本轮尚未添加检查或修改数据。
    -- >>> A3 [RECOMMENDED] -----------------------------------------------------
    -- >>> WAS: country_code TEXT NOT NULL PRIMARY KEY,
    -- >>> NOW: country_code TEXT NOT NULL PRIMARY KEY CHECK (country_code ~ '^[A-Z]{3}$'),
    -- >>> WHY: Enforces the three-capital-letter shape of K02 above. '~' means 'matches the
    -- >>>      pattern'. It cannot prove ISO membership: the provided files use race codes
    -- >>>      (GER, NED, SLO ...) that are not ISO, and all 29 of them pass this check.
    -- >>> ----------------------------------------------------------------------
    country_code TEXT NOT NULL PRIMARY KEY CHECK (country_code ~ '^[A-Z]{3}$'),
    -- [部分 K08] A p1 §1 要记录国家名称；当前可为 NULL，完整数据政策需明确。
    -- >>> A4 [REQUIRED] --------------------------------------------------------
    -- >>> WAS: country_name TEXT
    -- >>> NOW: country_name TEXT NOT NULL UNIQUE
    -- >>> WHY: Brief p1 point 1: 'For each country, we record the country code and country
    -- >>>      name.' UNIQUE: two countries cannot share a name. Supersedes K08 above.
    -- >>> ----------------------------------------------------------------------
    country_name TEXT NOT NULL UNIQUE
);

-- [已实现 K03/R01] A p1 §2；E Team 键、associated_with 两端基数。
-- [已实现 R03] T05+T07 要求存在本队队长，间接保证每队至少一位 Rider。
-- 提交时不能存在空队；事务中允许暂时先插车队再插队长。
-- [待确认 D04] Background 的 normally eight 不是恰好八人的硬约束。
CREATE TABLE Team (
    -- T01 PK：车队名称唯一标识车队，不允许重复。
    -- T02 NOT NULL：车队名称不能为 NULL。
    team_name TEXT NOT NULL PRIMARY KEY,
    -- T03 NOT NULL：每支车队必须填写一个国家代码。
    -- T04 FK：该国家代码必须存在于 Country；多个车队可以属于同一国家。
    country_code TEXT NOT NULL REFERENCES Country(country_code),
    -- T05 NOT NULL：每支车队必须指定队长。
    -- T06 UNIQUE：同一个骑手号码最多作为一支车队的队长。
    -- [已实现 R11/R12] A p1 Background 指定队长；E lead 为 Team(1,1)、
    -- Rider(0,1)，E note 2 明确队长必须属于本队。
    leader_bib INT NOT NULL UNIQUE
