-- Standings after every stage. Only riders still in the race are ranked.
CREATE VIEW v_gc_progress AS
WITH cum AS (
    SELECT f.rider_key, s.stage_id,
           SUM(f.adjusted_time) OVER (PARTITION BY f.rider_key ORDER BY s.stage_id) AS cum_adjusted,
           COUNT(*) OVER (PARTITION BY f.rider_key ORDER BY s.stage_id) AS stages_ridden
    FROM fact_results f JOIN dim_stage s USING (stage_key)
)
SELECT rider_key, stage_id, cum_adjusted,
       RANK() OVER (PARTITION BY stage_id ORDER BY cum_adjusted) AS gc_rank,
       cum_adjusted - MIN(cum_adjusted) OVER (PARTITION BY stage_id) AS gap_to_leader
FROM cum
WHERE stages_ridden = stage_id;

-- Rider totals for the riders who completed all 21 stages.
CREATE VIEW v_rider_totals AS
SELECT r.rider_key, r.bib_number, r.rider_name, r.team_name, r.rider_country_code,
       r.rider_country_name, r.age_at_start, r.young_born_2000, r.young_at_start,
       SUM(f.adjusted_time) AS total_adjusted,
       SUM(f.finish_time) AS total_finish,
       SUM(f.time_bonus) AS total_bonus,
       SUM(f.time_penalty) AS total_penalty,
       SUM(f.is_win) AS wins, SUM(f.is_podium) AS podiums, SUM(f.is_top10) AS top10s
FROM fact_results f JOIN dim_rider r USING (rider_key)
WHERE r.race_status = 'Finished'
GROUP BY r.rider_key;

-- General Classification.
CREATE VIEW v_gc AS
SELECT RANK() OVER (ORDER BY total_adjusted) AS gc_rank,
       total_adjusted - MIN(total_adjusted) OVER () AS gap, *
FROM v_rider_totals;

-- Mountain proxy from the instructor's E4: adjusted time on Mountain stages only.
CREATE VIEW v_mountain_proxy AS
SELECT r.rider_key, SUM(f.adjusted_time) AS mountain_time,
       RANK() OVER (ORDER BY SUM(f.adjusted_time)) AS mountain_rank
FROM fact_results f
JOIN dim_rider r USING (rider_key)
JOIN dim_stage s USING (stage_key)
WHERE s.terrain = 'Mountain' AND r.race_status = 'Finished'
GROUP BY r.rider_key;

-- Finish points: the official stage-finish scale (Art. 24 b) applied to each
-- finisher's stage ranks. Intermediate sprints are not in the data, so this is
-- not the green jersey total. Ties: stage wins, then GC rank.
CREATE VIEW v_finish_points AS
WITH pts AS (
    SELECT f.rider_key, COALESCE(SUM(p.points), 0) AS finish_points, SUM(f.is_win) AS stage_wins
    FROM fact_results f
    JOIN dim_stage s USING (stage_key)
    LEFT JOIN ref_points_scale p ON p.coefficient = s.coefficient AND p.place = f.stage_rank
    GROUP BY f.rider_key
)
SELECT g.rider_key, p.finish_points, p.stage_wins,
       RANK() OVER (ORDER BY p.finish_points DESC, p.stage_wins DESC, g.gc_rank) AS points_rank
FROM v_gc g JOIN pts p USING (rider_key);

-- Team classification: the three fastest riders of each team on each stage.
CREATE VIEW v_team_classification AS
WITH ranked AS (
    SELECT f.team_key, f.stage_key, f.finish_time,
           ROW_NUMBER() OVER (PARTITION BY f.team_key, f.stage_key ORDER BY f.finish_time) AS rn
    FROM fact_results f
)
SELECT team_key, SUM(finish_time) AS team_time,
       RANK() OVER (ORDER BY SUM(finish_time)) AS team_rank
FROM ranked WHERE rn <= 3
GROUP BY team_key;

