    -- [部分 R04] A p2 §3 明确每人恰有一个国家；E come_from Rider(1,1)。
    -- 当前缺 NOT NULL，是实际不合规项，不能因原始数据缺失就放宽概念规则。
    -- [已实现 R05] A 明确骑手与车队国家可不同；不加两者相等的 CHECK。
    -- >>> A7 [COMMENT CORRECTION, code unchanged] ------------------------------
    -- >>> NOW: keep country_code nullable, as in the amended proposal
    -- >>> WHY: R04 and U04 say this column should be NOT NULL. Checked against riders.csv:
