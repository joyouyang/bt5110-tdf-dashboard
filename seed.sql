    -- 它只延迟此 FK，不延迟上面的 NOT NULL / UNIQUE。
    -- [实现选择] 联合 FK 是实现 E note 2 的方式；延迟检查 T08 是 SQLite
    -- 处理循环引用的执行策略，不是作业新增的一项业务规则。
    -- >>> A2 [REQUIRED] --------------------------------------------------------
    -- >>> WAS: FOREIGN KEY (leader_bib, team_name) REFERENCES Rider(bib_number, team_name)
    -- >>>      DEFERRABLE INITIALLY DEFERRED   (inside CREATE TABLE Team)
    -- >>> NOW: the same constraint, added with ALTER TABLE straight after CREATE TABLE Rider
    -- >>> WHY: PostgreSQL cannot point a foreign key at a table that does not exist yet, so
    -- >>>      this line stops with 'relation "rider" does not exist'. SQLite allows it. The
    -- >>>      rule itself (T07/T08) is unchanged. The comma after leader_bib was removed.
    -- >>> ----------------------------------------------------------------------
    -- FOREIGN KEY (leader_bib, team_name)
