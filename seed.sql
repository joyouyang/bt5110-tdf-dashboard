CREATE TABLE RiderExit (
    -- E01 PK：每位骑手最多有一条退赛记录（不是以骑手+赛段为联合主键）。
    -- E02 NOT NULL：退赛记录必须有骑手号码。
    -- E03 FK：该骑手必须存在于 Rider。
    bib_number INT NOT NULL PRIMARY KEY REFERENCES Rider(bib_number),
    -- E04 NOT NULL：必须指定骑手在其开始前退出的赛段 S（不是最后完成赛段）。
